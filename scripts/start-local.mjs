import { existsSync } from 'node:fs';
import { ROOT, TOOL, JAVA_HOME, PORTS } from './local-config.mjs';
import { runtimeEnv } from './env.mjs';
import { startInfra } from './infra.mjs';
import { start, waitFor } from './processes.mjs';
import { materializeBackendArtifact } from './runtime-artifact.mjs';
await startInfra();
if (process.argv.includes('--infra-only')) process.exit(0);
const jar = `${ROOT}/backend/ruoyi-admin/target/ruoyi-admin.jar`;
if (!existsSync(jar)) throw new Error('Backend jar missing; run scripts/build-local first');
const artifact = materializeBackendArtifact({ source: jar });
await start('backend', `${JAVA_HOME}/bin/java`, ['-jar', artifact.path, '--spring.profiles.active=p0'], runtimeEnv({ secrets: true }), { port: PORTS.backend });
await waitFor(async () => { try { return (await fetch(`http://127.0.0.1:${PORTS.backend}/api/public/v1/p0/health`)).ok; } catch { return false; } }, 45000);
await start('executor', `${TOOL}/node/bin/node`, [`${ROOT}/executor/server.mjs`], runtimeEnv(), { port: PORTS.executor });
for (const name of ['student', 'admin']) await start(name, `${TOOL}/node/bin/node`, [`${TOOL}/npm/bin/npm-cli.js`, '--prefix', `${ROOT}/${name}-web`, 'run', 'dev', '--', '--host', '127.0.0.1', '--port', String(PORTS[name]), '--strictPort'], runtimeEnv(), { port: PORTS[name] });
console.log(`P0 local-only: http://localhost:${PORTS.student} / http://localhost:${PORTS.admin} / mail http://127.0.0.1:${PORTS.mail}`);
